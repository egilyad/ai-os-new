// Generator: per-article "connections" — panel -> route -> component -> tests.
// Run: node scripts/gen-wiki-connections.mjs
// Output: src/generated/wiki-connections.ts (do not hand-edit).
// Used by the Wiki panel (WikiArticleView) to show the code chain for panel pages;
// the markdown mirror (gen-wiki-docs.mjs) renders the same chain from the lib.
import { writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { parseNavSections, routeImportComponents, techniqueComponents, testsFor, panelArticles } from './lib/route-nav.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const genDir = resolve(root, 'src/generated');
mkdirSync(genDir, { recursive: true });

const panelArticle = panelArticles();
const components = { ...routeImportComponents(), ...techniqueComponents() };

const byArticle = {};
for (const section of parseNavSections()) {
    for (const item of section.items) {
        const slug = panelArticle[item.id];
        if (!slug) continue;
        const component = components[item.id] ?? null;
        (byArticle[slug] ??= []).push({
            panelId: item.id,
            route: item.path ?? `/${item.id}`,
            component,
            tests: component ? testsFor(component) : [],
        });
    }
}

const out = [
    '// Generated by node scripts/gen-wiki-connections.mjs — do not hand-edit.',
    '',
    'export interface WikiConnection {',
    '    panelId: string;',
    '    route: string;',
    '    component: string | null;',
    '    tests: string[];',
    '}',
    '',
    '/** Panel -> code chain per wiki article slug (panels mapped to that article). */',
    `export const WIKI_CONNECTIONS: Record<string, WikiConnection[]> = ${JSON.stringify(byArticle, null, 4)};`,
    '',
].join('\n');

writeFileSync(resolve(genDir, 'wiki-connections.ts'), out, 'utf8');
console.log(`wiki connections: ${Object.keys(byArticle).length} articles -> src/generated/wiki-connections.ts`);
