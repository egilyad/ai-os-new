// Stage 8 generator: checks & metrics — one page that lists every objective
// check the project runs and reports completeness (coverage) over the real
// artifacts (manifest, inventory, graph) plus a live run of the docs-health
// checks. Makes the "state of the docs" verifiable at a glance.
// Run: node scripts/gen-wiki-checks.mjs
// Output: src/generated/wiki-checks.ts -> CHECKS_MARKDOWN
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { computeDocsHealth } from './lib/docs-health.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const genDir = resolve(root, 'src/generated');
mkdirSync(genDir, { recursive: true });

const manifest = JSON.parse(readFileSync(resolve(root, 'docs/manifest.json'), 'utf8'));
const inventory = JSON.parse(readFileSync(resolve(root, 'docs/inventory.json'), 'utf8'));
const graph = JSON.parse(readFileSync(resolve(root, 'docs/graph.json'), 'utf8'));
const h = computeDocsHealth(root);

const arts = manifest.articles;
const pct = (n, d) => (d ? Math.round((n / d) * 100) : 0);
const withSources = arts.filter((a) => (a.sources ?? []).length).length;
const withTests = arts.filter((a) => (a.tests ?? []).length).length;
const withRelated = arts.filter((a) => (a.related ?? []).length).length;
const withTags = arts.filter((a) => (a.tags ?? []).length).length;
const panelsCovered = manifest.panels.filter((p) => p.article).length;
const hardErrors = h.hardErrors ?? 0;

const md = [];
md.push('# Проверки и показатели');
md.push('');
md.push('> Автосгенерировано `scripts/gen-wiki-checks.mjs` из реальных артефактов (`docs/manifest.json`, `docs/inventory.json`, `docs/graph.json`) и живого прогона проверок.');
md.push('');
md.push('Документация проверяется объективно и прозрачно: у каждого числа есть источник и метод.');
md.push('Это сводка всех проверок проекта и отчёт о полноте. Правила — [[docs-standard]];');
md.push('подробности проверки — [[docs-health]].');
md.push('');
md.push('## Сводка проверок');
md.push('');
md.push('| Проверка | Инструмент | Результат |');
md.push('| --- | --- | --- |');
md.push(`| Ссылки на источники | \`docs:health\` | битых: ${h.brokenSources.length} |`);
md.push(`| Внутренние ссылки | \`docs:health\` | битых: ${h.brokenLinks.length} |`);
md.push(`| Схема стандарта | \`docs:health\` | проблем: ${h.schemaProblems.length} |`);
md.push(`| Манифест | \`docs:health\` | проблем: ${h.manifestProblems.length} |`);
md.push(`| Полнота статей | \`docs:health\` | неполных: ${h.incomplete.length} |`);
md.push(`| README → вики | \`docs:health\` | битых: ${h.brokenReadmeLinks.length}; паритет RU/EN: ${h.readmeParityDiff.length} |`);
md.push(`| Синхронизация генерации | CI «Wiki docs in sync» | \`git diff --exit-code\` по docs/wiki и src/generated |`);
md.push(`| Сборка и типы | CI (tsc -b, ESLint) | по job «quality» |`);
md.push(`| Тесты | CI (test:stable, e2e) | по соответствующим job |`);
md.push('');
md.push(hardErrors === 0 ? '**Итог: hard-ошибок нет.**' : `**Итог: hard-ошибок — ${hardErrors}.**`);
md.push('');
md.push('## Отчёт о полноте');
md.push('');
md.push('| Показатель | Значение | Покрытие |');
md.push('| --- | --- | --- |');
md.push(`| Статьи вики | ${arts.length} | — |`);
md.push(`| Статьи с источниками | ${withSources} | ${pct(withSources, arts.length)}% |`);
md.push(`| Статьи с тестами | ${withTests} | ${pct(withTests, arts.length)}% |`);
md.push(`| Статьи со связями | ${withRelated} | ${pct(withRelated, arts.length)}% |`);
md.push(`| Статьи с тегами | ${withTags} | ${pct(withTags, arts.length)}% |`);
md.push(`| Панели с документацией | ${panelsCovered}/${manifest.panels.length} | ${pct(panelsCovered, manifest.panels.length)}% |`);
md.push(`| Документы в инвентаре | ${inventory.totals.documents} | дублей содержимого: ${inventory.duplicates.content.length} |`);
md.push(`| Узлы графа знаний | ${graph.stats.nodes} | рёбер: ${graph.stats.edges} |`);
md.push('');
md.push('## Где смотреть');
md.push('');
md.push('- Полный отчёт проверки — `npm run docs:health`, статья [[docs-health]].');
md.push('- Состав документации — [[docs-inventory]]; карта — [[docs-index]].');
md.push('- Связи сущностей — [[dev-graph]]; генераторы — [[dev-generators]].');
md.push('');
md.push('## Как это считается');
md.push('');
md.push('- Числа покрытия — из `docs/manifest.json` (статьи/панели) и `docs/inventory.json`.');
md.push('- Проблемы проверок — живой прогон `scripts/lib/docs-health.mjs` (та же логика, что у `docs:health`).');
md.push('- Статусы CI — по шагам workflow `.github/workflows/ci.yml`.');
md.push('- Источник: `scripts/gen-wiki-checks.mjs` → `src/generated/wiki-checks.ts` → эта страница.');
md.push('');

writeFileSync(
    resolve(genDir, 'wiki-checks.ts'),
    `// Generated by node scripts/gen-wiki-checks.mjs — do not hand-edit.\nexport const CHECKS_MARKDOWN: string = ${JSON.stringify(md.join('\n'))};\n`,
);
console.log(
    `checks: hard ${hardErrors}, sources ${pct(withSources, arts.length)}%, tests ${pct(withTests, arts.length)}%, panels ${pct(panelsCovered, manifest.panels.length)}% -> src/generated/wiki-checks.ts`,
);
