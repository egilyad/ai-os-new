// Generator: wiki dynamic data — recent commits feed + panel→component map.
// Run: node scripts/gen-wiki-data.mjs (re-run to refresh; output is generated, do not hand-edit).
// Commits: git log (needs full history; CI must use fetch-depth: 0).
// Fallback when git is unavailable: empty feed (UI shows a notice, never fake news).
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const __filename = fileURLToPath(import.meta.url);
const root = resolve(dirname(__filename), '..');
const outDir = resolve(root, 'src/generated');

function commitFeed() {
    const fallback = { generatedAt: new Date().toISOString(), commits: [], truncated: false };
    try {
        const raw = execFileSync(
            'git',
            ['log', '--pretty=format:%H%x1f%ad%x1f%s%x1f%b', '--date=iso', '-n', '40'],
            { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] },
        );
        const commits = raw
            .split('\n')
            .filter(Boolean)
            .map((line) => {
                const [hash, date, subject, body] = line.split('');
                return {
                    hash: (hash || '').slice(0, 12),
                    date: date || '',
                    subject: subject || '',
                    body: (body || '').slice(0, 500),
                };
            })
            .filter((c) => c.hash && c.subject);
        return { generatedAt: new Date().toISOString(), commits, truncated: commits.length >= 40 };
    } catch {
        return fallback;
    }
}

function panelMap() {
    // route-imports.ts map literal: 'panel-id': ComponentName + lazy imports above.
    const src = readFileSync(resolve(root, 'src/route-imports.ts'), 'utf8');
    const map = {};
    // Lazy declarations: const XxxLazy = React.lazy(() => import('./components/...'));
    const declRe = /const\s+(\w+)\s*=\s*React\.lazy\(\s*\(\)\s*=>\s*import\('([^']+)'\)/g;
    const decls = {};
    let m;
    while ((m = declRe.exec(src))) decls[m[1]] = m[2];
    // Map entries: 'id': Name,  (also bare `logs: LogsPanel,` form)
    const mapRe = /^\s*'?([\w-]+)'?:\s*(\w+),?\s*$/gm;
    while ((m = mapRe.exec(src))) {
        const id = m[1];
        const comp = m[2];
        if (decls[comp]) map[id] = decls[comp].replace(/^\.\//, 'src/');
    }
    return map;
}

mkdirSync(outDir, { recursive: true });
const feed = commitFeed();
writeFileSync(
    resolve(outDir, 'commits-feed.ts'),
    `// Generated by node scripts/gen-wiki-data.mjs — do not hand-edit.\nexport interface WikiCommitEntry {\n  hash: string;\n  date: string;\n  subject: string;\n  body: string;\n}\nexport interface WikiCommitsFeed {\n  generatedAt: string;\n  commits: WikiCommitEntry[];\n  truncated: boolean;\n}\nexport const COMMITS_FEED: WikiCommitsFeed = ${JSON.stringify(feed, null, 2)};\n`,
);
const panels = panelMap();
writeFileSync(
    resolve(outDir, 'wiki-panel-map.ts'),
    `// Generated by node scripts/gen-wiki-data.mjs — do not hand-edit.\nexport const WIKI_PANEL_MAP: Record<string, string> = ${JSON.stringify(panels, null, 2)};\n`,
);
console.log(`commits: ${feed.commits.length}, panel map: ${Object.keys(panels).length}`);
