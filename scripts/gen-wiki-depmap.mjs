import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcFile = resolve(root, 'src/kernel/DEPENDENCY_MAP.md');
const outFile = resolve(root, 'src/generated/wiki-dep-map.ts');

let md = readFileSync(srcFile, 'utf8').replace(/\r\n/g, '\n').trimEnd();
// Drop the file's own H1 so it does not clash with the wiki article title.
md = md.replace(/^#\s+.*\n+/, '');
const intro =
    'Карта зависимостей DI ядра — кто кого инжектит. A → B означает «A зависит от B». Источник: src/kernel/DEPENDENCY_MAP.md (v4.5.0).';

const L = [];
L.push('## Карта зависимостей ядра');
L.push('');
L.push(intro.trimEnd());
L.push('');
L.push(
    'Если добавляешь сервис — зарегистрируй его в фазе bootstrap, получи зависимости через constructor(deps) и обнови этот файл-источник, затем перезапусти генератор.',
);
L.push('');
L.push(md);
L.push('');

const out = `// Generated by node scripts/gen-wiki-depmap.mjs — do not hand-edit.
export const DEP_MAP_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
export const DEP_MAP_MARKDOWN: string = ${JSON.stringify(L.join('\n'))};
`;
writeFileSync(outFile, out, 'utf8');
console.log(`dep map markdown: ${L.join('\n').length} chars`);
