// Generator: test-surface catalog for the wiki — how many tests exist per area,
// which paths form the CI gate (test:stable), and the server/e2e suites.
// Run: node scripts/gen-wiki-tests.mjs  (output is generated, do not hand-edit).
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve, relative } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir, acc = []) {
    if (!existsSync(dir)) return acc;
    for (const e of readdirSync(dir, { withFileTypes: true })) {
        const p = resolve(dir, e.name);
        if (e.isDirectory()) {
            if (e.name === 'node_modules' || e.name.startsWith('.')) continue;
            walk(p, acc);
        } else {
            acc.push(p);
        }
    }
    return acc;
}

const srcTests = walk(resolve(root, 'src'))
    .filter((p) => /\.test\.(ts|tsx)$/.test(p))
    .map((p) => relative(resolve(root, 'src'), p).replace(/\\/g, '/'));

const byArea = new Map();
for (const rel of srcTests) {
    const area = rel.includes('/') ? rel.split('/')[0] : '(root)';
    byArea.set(area, (byArea.get(area) || 0) + 1);
}
const areas = [...byArea.entries()].sort((a, b) => b[1] - a[1]);
const areaLabel = (a) => (a === '(root)' ? 'src (корень)' : `src/${a}`);

const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const stablePaths = (pkg.scripts?.['test:stable'] || '')
    .replace(/^vitest run\s*/, '')
    .split(/\s+/)
    .filter((s) => s && !s.startsWith('--'));

const serverTests = existsSync(resolve(root, 'server/tests'))
    ? readdirSync(resolve(root, 'server/tests')).filter((n) => n.endsWith('.mjs')).sort()
    : [];
const scriptTests = existsSync(resolve(root, 'scripts/tests'))
    ? readdirSync(resolve(root, 'scripts/tests')).filter((n) => n.endsWith('.mjs')).sort()
    : [];
const e2eTests = existsSync(resolve(root, 'e2e'))
    ? readdirSync(resolve(root, 'e2e')).filter((n) => /\.spec\.ts$/.test(n)).sort()
    : [];

const totalSrc = srcTests.length;
const totalAll = totalSrc + serverTests.length + scriptTests.length + e2eTests.length;

const L = [];
L.push('## Тесты');
L.push('');
L.push(
    `Тестовая поверхность: ${totalSrc} unit/компонентных тестов в src, ${serverTests.length} server-тестов (node --test), ${scriptTests.length} тестов скриптов, ${e2eTests.length} e2e (Playwright) — всего ${totalAll}. CI гоняет стабильный набор ([[dev-ci]]), а не все сразу: полный vitest на общих раннерах не тянет.`,
);
L.push('');
L.push('```mermaid');
L.push('flowchart LR');
L.push('    U["src/**/*.test.ts(x) — Vitest"] --> G["test:stable — гейт CI"]');
L.push('    S["server/tests — node --test"] --> C["CI"]');
L.push('    E["e2e/*.spec.ts — Playwright"] --> C');
L.push('    G --> C');
L.push('```');
L.push('');
L.push('### Unit/компонентные тесты по областям (src)');
L.push('');
L.push('| Область | Тестов |');
L.push('|---|---|');
for (const [area, n] of areas) L.push(`| ${areaLabel(area)} | ${n} |`);
L.push('');
L.push(`### Стабильный гейт CI — test:stable (${stablePaths.length} путей)`);
L.push('');
L.push('| Путь из package.json |');
L.push('|---|');
for (const p of stablePaths) L.push(`| ${p} |`);
L.push('');
if (serverTests.length) {
    L.push('### Server-тесты (node --test)');
    L.push('');
    L.push('| Файл |');
    L.push('|---|');
    for (const n of serverTests) L.push(`| server/tests/${n} |`);
    L.push('');
}
if (scriptTests.length) {
    L.push('### Тесты скриптов');
    L.push('');
    L.push('| Файл |');
    L.push('|---|');
    for (const n of scriptTests) L.push(`| scripts/tests/${n} |`);
    L.push('');
}
if (e2eTests.length) {
    L.push('### E2E (Playwright)');
    L.push('');
    L.push('| Спека |');
    L.push('|---|');
    for (const n of e2eTests) L.push(`| e2e/${n} |`);
    L.push('');
}

const md = L.join('\n');
const out = `// Generated by node scripts/gen-wiki-tests.mjs — do not hand-edit.
export const TESTS_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
export const TESTS_SRC_COUNT = ${totalSrc};
export const TESTS_MARKDOWN: string = ${JSON.stringify(md)};
`;
writeFileSync(resolve(root, 'src/generated/wiki-tests.ts'), out, 'utf8');
console.log(
    `src tests: ${totalSrc}, areas: ${areas.length}, stable paths: ${stablePaths.length}, server: ${serverTests.length}, script: ${scriptTests.length}, e2e: ${e2eTests.length}, markdown=${md.length}`,
);
