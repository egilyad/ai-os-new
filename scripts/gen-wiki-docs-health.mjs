// Generator: the "Documentation Health" wiki article, built from a real run of
// the docs-health checks (same logic as `npm run docs:health`).
// Run: node scripts/gen-wiki-docs-health.mjs
// Output: src/generated/wiki-docs-health.ts -> DOCS_HEALTH_MARKDOWN
// The article is part of the wiki corpus (src/components/WikiPanel/wiki-catalog.ts),
// so it renders in the app, on GitHub (docs/wiki) and on the static site.
import { writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { computeDocsHealth } from './lib/docs-health.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const genDir = resolve(root, 'src/generated');
mkdirSync(genDir, { recursive: true });

const h = computeDocsHealth(root);
const cap = (arr) => (arr.length > 20 ? [...arr.slice(0, 20), `… +${arr.length - 20} ещё`] : arr);

const md = [];
md.push('# Здоровье документации');
md.push('');
md.push('> Автосгенерировано `scripts/gen-wiki-docs-health.mjs` из реального прогона проверки.');
md.push('> Не редактировать вручную — обновляется вместе с викой.');
md.push('');
md.push('Документация — такой же артефакт системы, как код: её можно проверять объективно.');
md.push('Эта страница собирается из тех же проверок, что гоняет CI (`npm run docs:health`),');
md.push('и показывает, *откуда* берётся каждое число.');
md.push('');
md.push('## Показатели');
md.push('');
md.push('| Показатель | Значение | Как считается |');
md.push('| --- | --- | --- |');
md.push(`| Статей проверено | ${h.articles} | файлы \`docs/wiki/*.md\`, кроме индекса и этой страницы |`);
md.push(`| Битые ссылки на исходники | ${h.brokenSources.length} | пути из строки «Источники:» резолвятся как модули (расширение / index / glob) |`);
md.push(`| Битые внутренние ссылки | ${h.brokenLinks.length} | markdown-ссылки внутри статей ведут на существующие файлы |`);
md.push(`| Неполные статьи | ${h.incomplete.length} | текст короче 250 символов или пометка «пока не написана» |`);
md.push(`| Статьи без источников | ${h.noSources.length} | отсутствует строка «Источники:» |`);
md.push(`| Панели с документацией | ${h.mapped.size}/${h.allPanels.length} | панели из реестра маршрутов сопоставлены со статьёй |`);
md.push(`| &nbsp;&nbsp;авто-панели техник | ${h.techniquePanels.length} | покрыты статьёй [[panels-catalog]], пробелом не считаются |`);
md.push(`| Проблемы манифеста | ${h.manifestProblems.length} | ссылки в \`docs/manifest.json\` резолвятся |`);
md.push(`| README → вики | ${h.readmeRu.slugs.length} (RU) / ${h.readmeEn.slugs.length} (EN) | ссылки README.md и README_EN.md в \`docs/wiki/*.md\` резолвятся |`);
md.push(`| README RU/EN расхождение | ${h.readmeParityDiff.length} | разница наборов статей между README.md и README_EN.md |`);
md.push(`| Статьи вне README | ${h.readmeOrphans.length} | статьи вики, не залинкованные из README.md |`);
md.push('');
md.push(
    h.hardErrors === 0
        ? 'Итог: **здорово** — hard-ошибок нет.'
        : `Итог: **есть проблемы** — hard-ошибок: ${h.hardErrors}.`,
);
md.push('');
md.push('## Что требует внимания');
md.push('');
const attention = [];
if (h.brokenSources.length) {
    attention.push(`Битые источники (${h.brokenSources.length}):`, ...cap(h.brokenSources).map((b) => `- ${b.slug} → \`${b.source}\``), '');
}
if (h.brokenLinks.length) {
    attention.push(`Битые ссылки (${h.brokenLinks.length}):`, ...cap(h.brokenLinks).map((b) => `- ${b.slug} → ${b.href}`), '');
}
if (h.manifestProblems.length) {
    attention.push(`Проблемы манифеста (${h.manifestProblems.length}):`, ...cap(h.manifestProblems).map((b) => `- ${b}`), '');
}
if (h.brokenReadmeLinks.length) {
    attention.push(`Битые ссылки README (${h.brokenReadmeLinks.length}):`, ...cap(h.brokenReadmeLinks).map((b) => `- ${b.file} → ${b.slug}.md`), '');
}
if (h.undocumented.length) {
    attention.push(
        `Панели без статьи (${h.undocumented.length}):`,
        ...cap(h.undocumented).map((p) => `- ${p.id} (${p.section})`),
        '',
    );
}
if (h.readmeParityDiff.length) {
    attention.push(`README RU/EN расхождение (${h.readmeParityDiff.length}):`, ...cap(h.readmeParityDiff).map((b) => `- ${b}`), '');
}
if (!attention.length) attention.push('Проблем не найдено.');
md.push(...attention);
md.push('## Как это проверяется');
md.push('');
md.push('- Логика: `scripts/lib/docs-health.mjs` — одна на CLI и на эту страницу.');
md.push('- CLI: `npm run docs:health` — печатает отчёт и падает при hard-ошибках.');
md.push('- Эта страница: `npm run gen:wiki-docs-health` → `src/generated/wiki-docs-health.ts`.');
md.push('- CI (job quality): шаг «Documentation health» гоняет CLI; «Wiki docs in sync» проверяет,');
md.push('  что страница и зеркало не устарели. Больше о генераторах — в [[dev-generators]].');

writeFileSync(
    resolve(genDir, 'wiki-docs-health.ts'),
    `// Generated by node scripts/gen-wiki-docs-health.mjs — do not hand-edit.\nexport const DOCS_HEALTH_MARKDOWN: string = ${JSON.stringify(md.join('\n'))};\n`,
);
console.log(
    `docs-health article: ${h.articles} articles, hard errors ${h.hardErrors} -> src/generated/wiki-docs-health.ts`,
);
