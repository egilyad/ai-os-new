// Stage 2 generator: the documentation standard. From ONE source
// (scripts/lib/entity-model.mjs) it produces both the machine-readable model
// (docs/entity-model.json, for agents) and the Russian wiki article
// (src/generated/wiki-docs-standard.ts -> DOCS_STANDARD_MARKDOWN).
// Run: node scripts/gen-wiki-docs-standard.mjs
import { writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { STANDARD } from './lib/entity-model.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const genDir = resolve(root, 'src/generated');
mkdirSync(genDir, { recursive: true });

const yn = (b) => (b ? 'да' : 'нет');

const md = [];
md.push('# Стандарт документации');
md.push('');
md.push('> Автосгенерировано `scripts/gen-wiki-docs-standard.mjs` из `scripts/lib/entity-model.mjs`.');
md.push('> Не редактировать вручную — правьте источник и перегенерируйте.');
md.push('');
md.push(...STANDARD.purpose);
md.push('');
md.push(`Версия стандарта: **${STANDARD.version}**. Машиночитаемая форма — ` +
    '`docs/entity-model.json` (для агентов и инструментов).');
md.push('');
md.push('## Категории документации');
md.push('');
md.push('| Категория | Где | Назначение | Генерируется |');
md.push('| --- | --- | --- | --- |');
for (const c of STANDARD.categories) md.push(`| ${c.id} | \`${c.where}\` | ${c.role} | ${yn(c.generated)} |`);
md.push('');
md.push('## Карточка сущности');
md.push('');
md.push('Единый набор полей для любой сущности (статья, панель, сервис, событие).');
md.push('«Авто» — поле заполняется генератором; остальные — вручную и не стираются.');
md.push('');
md.push('| Поле | Обязательное | Авто | Что содержит | В вики-манифесте |');
md.push('| --- | --- | --- | --- | --- |');
for (const f of STANDARD.entityModel) md.push(`| \`${f.name}\` | ${yn(f.required)} | ${yn(f.auto)} | ${f.contains} | \`${f.mapsTo}\` |`);
md.push('');
md.push('## Статусы достоверности');
md.push('');
md.push('**Статус реализации ≠ статус проверки.** «Реализовано» и «проверено» — разное,');
md.push('и смешивать их нельзя. Поэтому статусы разделены по измерениям.');
md.push('');
md.push('| ID | По-русски | Измерение | Смысл |');
md.push('| --- | --- | --- | --- |');
for (const s of STANDARD.statuses) md.push(`| \`${s.id}\` | ${s.ru} | ${s.dimension} | ${s.meaning} |`);
md.push('');
md.push('### Соответствие текущим статусам вики');
md.push('');
md.push('В корпусе вики поле статуса (freshness) уже используется; оно отображается так:');
md.push('');
md.push('| Значение в вики | По-русски | Статус достоверности |');
md.push('| --- | --- | --- |');
for (const m of STANDARD.freshnessMap) md.push(`| \`${m.freshness}\` | ${m.ru} | \`${m.status}\` |`);
md.push('');
md.push('## Источники истины');
md.push('');
md.push('Что считается первоисточником по каждому типу утверждений.');
md.push('');
md.push('| О чём | Источник | Как проверить |');
md.push('| --- | --- | --- |');
for (const s of STANDARD.sourcesOfTruth) md.push(`| ${s.subject} | ${s.source} | ${s.check} |`);
md.push('');
md.push('## Идентификаторы');
md.push('');
md.push('| Тип | Схема | Пример |');
md.push('| --- | --- | --- |');
for (const i of STANDARD.idConventions) md.push(`| ${i.kind} | \`${i.pattern}\` | \`${i.example}\` |`);
md.push('');
md.push('## Политика языков');
md.push('');
md.push(`- **Основной язык:** \`${STANDARD.languagePolicy.primary}\`. ${STANDARD.languagePolicy.note}`);
md.push(`- **Английский:** \`${STANDARD.languagePolicy.english.file}\` — статус \`${STANDARD.languagePolicy.english.status}\`.`);
md.push(`  ${STANDARD.languagePolicy.english.detail}`);
md.push('');
md.push('## Правила истории');
md.push('');
for (const r of STANDARD.historyRules) md.push(`- ${r}`);
md.push('');
md.push('## Как это связано');
md.push('');
md.push('- Источник стандарта: `scripts/lib/entity-model.mjs`; JSON: `docs/entity-model.json`.');
md.push('- Генератор: `npm run gen:wiki-docs-standard` → `src/generated/wiki-docs-standard.ts`.');
md.push('- Состояние документации по этому стандарту — [[docs-health]]; состав — [[docs-inventory]].');
md.push('- Числа и связи сущностей — в `docs/manifest.json`; список генераторов — [[dev-generators]].');

const json = JSON.stringify(STANDARD, null, 2) + '\n';
writeFileSync(resolve(root, 'docs/entity-model.json'), json);
writeFileSync(
    resolve(genDir, 'wiki-docs-standard.ts'),
    `// Generated by node scripts/gen-wiki-docs-standard.mjs — do not hand-edit.\nexport const DOCS_STANDARD_MARKDOWN: string = ${JSON.stringify(md.join('\n'))};\n`,
);
console.log(
    `docs standard: ${STANDARD.statuses.length} statuses, ${STANDARD.entityModel.length} fields, ` +
        `${STANDARD.sourcesOfTruth.length} sources -> docs/entity-model.json + src/generated/wiki-docs-standard.ts`,
);
