// Generator: kernel contracts catalog for the wiki — exported interfaces/types in
// src/kernel/contracts, plus which kernel files implement each one.
// Run: node scripts/gen-wiki-contracts.mjs  (output is generated, do not hand-edit).
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve, relative } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir, filter, acc = []) {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
        const p = resolve(dir, e.name);
        if (e.isDirectory()) {
            if (e.name === 'node_modules') continue;
            walk(p, filter, acc);
        } else if (filter(e.name)) {
            acc.push(p);
        }
    }
    return acc;
}

const declRe = /export\s+(?:abstract\s+)?(interface|type)\s+([A-Za-z0-9_]+)/g;
const implRe = /implements\s+([A-Za-z0-9_.,\s]+?)(?:\{|$)/gm;

const contractFiles = walk(resolve(root, 'src/kernel/contracts'), (n) => n.endsWith('.ts') && !n.endsWith('.test.ts'));
const kernelFiles = walk(resolve(root, 'src/kernel'), (n) => n.endsWith('.ts') && !n.endsWith('.test.ts')).filter(
    (p) => !p.replace(/\\/g, '/').includes('/kernel/contracts/'),
);

const implByContract = new Map();
for (const abs of kernelFiles) {
    const rel = 'src/' + relative(resolve(root, 'src'), abs).replace(/\\/g, '/');
    const text = readFileSync(abs, 'utf8');
    implRe.lastIndex = 0;
    let m;
    while ((m = implRe.exec(text)) !== null) {
        for (const raw of m[1].split(',')) {
            const name = raw.trim().split(/[<\s]/)[0];
            if (!name) continue;
            if (!implByContract.has(name)) implByContract.set(name, new Set());
            implByContract.get(name).add(rel);
        }
    }
}

const rows = [];
let ifaceCount = 0;
let typeCount = 0;
for (const abs of contractFiles) {
    const rel = 'src/' + relative(resolve(root, 'src'), abs).replace(/\\/g, '/');
    const fromContracts = relative(resolve(root, 'src/kernel/contracts'), abs).replace(/\\/g, '/');
    const sub = fromContracts.split('/')[0];
    const folder = sub.endsWith('.ts') ? '(root)' : sub;
    const text = readFileSync(abs, 'utf8');
    declRe.lastIndex = 0;
    const names = [];
    let m;
    while ((m = declRe.exec(text)) !== null) {
        names.push({ kind: m[1], name: m[2] });
        if (m[1] === 'interface') ifaceCount++;
        else typeCount++;
    }
    for (const n of names) {
        const impls = implByContract.get(n.name);
        rows.push({ folder, file: rel, kind: n.kind, name: n.name, impls: impls ? [...impls].sort() : [] });
    }
}

rows.sort((a, b) => a.folder.localeCompare(b.folder) || a.file.localeCompare(b.file) || a.name.localeCompare(b.name));
const folders = [...new Set(rows.map((r) => r.folder))];

const L = [];
L.push('## Контракты ядра');
L.push('');
L.push(
    `Интерфейсы и типы-контракты слоя ядра (src/kernel/contracts): ${contractFiles.length} файл, ${rows.length} экспортов (${ifaceCount} interface, ${typeCount} type). Контракт — единственная поверхность ядра, которую разрешено импортировать коду UI; реализации живут в services и передаются через DI.`,
);
L.push('');
L.push('```mermaid');
L.push('flowchart LR');
L.push('    UI["UI / Application"] -- "импорт контракта" --> C["kernel/contracts — интерфейс"]');
L.push('    C -. "реализует" .-> S["kernel/services или kernel root — класс"]');
L.push('    S -. "инъекция через container" .-> UI');
L.push('```');
L.push('');
for (const f of folders) {
    const group = rows.filter((r) => r.folder === f);
    L.push(`### ${f} (${group.length})`);
    L.push('');
    L.push('| Контракт | Вид | Файл | Реализации в ядре |');
    L.push('|---|---|---|---|');
    for (const r of group) {
        const impls = r.impls.length ? r.impls.join(', ') : '—';
        L.push(`| ${r.name} | ${r.kind} | ${r.file} | ${impls} |`);
    }
    L.push('');
}

const md = L.join('\n');
const out = `// Generated by node scripts/gen-wiki-contracts.mjs — do not hand-edit.
export const CONTRACTS_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
export const CONTRACTS_COUNT = ${rows.length};
export const CONTRACTS_MARKDOWN: string = ${JSON.stringify(md)};
`;
writeFileSync(resolve(root, 'src/generated/wiki-contracts.ts'), out, 'utf8');
console.log(
    `contracts: files=${contractFiles.length}, exports=${rows.length} (iface=${ifaceCount}, type=${typeCount}), folders=${folders.length}, markdown=${md.length} chars`,
);
