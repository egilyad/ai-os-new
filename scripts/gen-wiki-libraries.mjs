// Stage B generator: external libraries catalog, straight from package.json.
// Honest scope: direct dependencies and their declared ranges only; licenses and
// actual transitive trees are not audited here (npm audit is a separate CI job).
// Run: node scripts/gen-wiki-libraries.mjs
// Output: src/generated/wiki-libraries.ts -> LIBRARIES_MARKDOWN
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const genDir = resolve(root, 'src/generated');
mkdirSync(genDir, { recursive: true });

const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const runtime = Object.entries(pkg.dependencies ?? {}).sort(([a], [b]) => a.localeCompare(b));
const dev = Object.entries(pkg.devDependencies ?? {}).sort(([a], [b]) => a.localeCompare(b));

const md = [];
md.push('# Внешние библиотеки');
md.push('');
md.push('> Автосгенерировано `scripts/gen-wiki-libraries.mjs` из `package.json`. Не редактировать вручную.');
md.push('');
md.push(`Прямые зависимости проекта: **${runtime.length}** runtime и **${dev.length}** dev.`);
md.push('Версии — объявленные диапазоны, а не зафиксированные в lock-файле; лицензии и');
md.push('транзитивное дерево здесь не проверяются (`npm audit` — отдельный job CI).');
md.push('');
md.push(`## Runtime (${runtime.length})`);
md.push('');
md.push('| Пакет | Версия |');
md.push('| --- | --- |');
for (const [name, version] of runtime) md.push(`| \`${name}\` | ${version} |`);
md.push('');
md.push(`## Dev (${dev.length})`);
md.push('');
md.push('| Пакет | Версия |');
md.push('| --- | --- |');
for (const [name, version] of dev) md.push(`| \`${name}\` | ${version} |`);
md.push('');
md.push('## Как обновляется');
md.push('');
md.push('- Источник истины — `package.json`; после изменения зависимостей запустите `node scripts/gen-wiki-libraries.mjs`.');
md.push('- Проверка уязвимостей — отдельный job «Security Audit» (`npm audit`), не этот каталог.');
md.push('- Связанные страницы: [[dev-overview]], [[dev-scripts]], [[dev-conventions]].');
md.push('');

writeFileSync(
    resolve(genDir, 'wiki-libraries.ts'),
    `// Generated by node scripts/gen-wiki-libraries.mjs — do not hand-edit.\nexport const LIBRARIES_MARKDOWN: string = ${JSON.stringify(md.join('\n'))};\n`,
    'utf8',
);
console.log(`libraries: ${runtime.length} runtime, ${dev.length} dev -> src/generated/wiki-libraries.ts`);
