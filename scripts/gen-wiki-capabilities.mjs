// Stage 6 generator: capabilities & scenarios — what a user can actually do,
// derived from the navigation registries (code truth), plus pointers to the
// how-to guides, a visual diagram, honest limitations and diagnostics.
// Run: node scripts/gen-wiki-capabilities.mjs
// Output: src/generated/wiki-capabilities.ts -> CAPABILITIES_MARKDOWN
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { navLabels, parseNavSections, panelArticles } from './lib/route-nav.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const genDir = resolve(root, 'src/generated');
mkdirSync(genDir, { recursive: true });

const REPO = 'https://github.com/egilyad/ai-os-new';
const gh = (p) => `${REPO}/blob/main/${p}`;

const labels = navLabels('ru');
const sections = parseNavSections();
const articles = panelArticles();

// count mermaid diagrams in the wiki source corpus (not the generated mirror,
// so this page does not count itself).
function countMermaid(dir) {
    let n = 0;
    for (const f of readdirSync(dir)) {
        if (!/\.tsx?$/.test(f)) continue;
        n += (readFileSync(resolve(dir, f), 'utf8').match(/```mermaid/g) || []).length;
    }
    return n;
}
const mermaidCount = countMermaid(resolve(root, 'src/components/WikiPanel')) + countMermaid(genDir);

const md = [];
md.push('# Возможности и сценарии');
md.push('');
md.push('> Автосгенерировано `scripts/gen-wiki-capabilities.mjs` из реестров маршрутов (`route-registry-*.ts`) и навигации. Не редактировать вручную.');
md.push('');
md.push('Что можно делать в SuperAgents OS и где об этом читать. Обзор возможностей —');
md.push('[[capabilities]]; справочник по панелям — [[panels-guide]] и [[panels-catalog]].');
md.push('');
md.push('## Области возможностей');
md.push('');
md.push('Навигация задаёт пользовательские области; в каждой — свои панели:');
md.push('');
md.push('| Область | Панелей | Примеры |');
md.push('| --- | --- | --- |');
for (const s of sections) {
    const title = labels.get(s.labelKey) || s.labelKey || s.id;
    const examples = [...new Set(
        s.items.map((it) => {
            const label = labels.get(it.labelKey) || it.id;
            const slug = articles[it.id];
            return slug ? `[[${slug}]]` : label;
        }),
    )]
        .slice(0, 3)
        .join(', ');
    if (!examples) continue;
    md.push(`| ${title} | ${s.items.length} | ${examples} |`);
}
md.push('');
md.push(`Всего панелей в навигации: **${sections.reduce((a, s) => a + s.items.length, 0)}**.`);
md.push('');
md.push('## Сквозные сценарии');
md.push('');
md.push('Пользовательские пути «действие → результат» собраны в справочниках:');
md.push('');
md.push(`- [USER ACTION → RESULT](${gh('docs/reference/USER_ACTION_MAP.md')}) — 5 канонов, карта без кода.`);
md.push(`- [Карта пользовательского управления](${gh('docs/reference/USER_CONTROL_MAP.md')}) — сервисы → понятная OS.`);
md.push(`- [CAPABILITY MATRIX](${gh('docs/reference/CAPABILITY_MATRIX.md')}) — матрица возможностей (статически проверенная).`);
md.push('');
md.push('## Руководства и примеры');
md.push('');
md.push('- Пошаговый обзор панелей — [[panels-guide]]; полный каталог — [[panels-catalog]].');
md.push('- Рецепты типовых задач — [[dev-cookbook]]; вход для разработчика — [[for-developers]].');
md.push('- Как всё устроено внутри — [[architecture]], [[dev-system-map]].');
md.push('');
md.push('## Визуальные материалы');
md.push('');
md.push(`В вики ${mermaidCount} диаграмм Mermaid. Ниже — карта слоёв системы:`);
md.push('');
md.push('```mermaid');
md.push('flowchart LR');
md.push('    UI[Панели и маршруты] --> Core[Сервисы ядра]');
md.push('    Core --> Events[События]');
md.push('    Core --> Stores[Хранилища]');
md.push('    Core --> Providers[Провайдеры]');
md.push('    Core --> Memory[Память и знания]');
md.push('    Providers --> Models[LLM-модели]');
md.push('```');
md.push('');
md.push('## Ограничения');
md.push('');
md.push('- Технические панели (техники) — их 84; это шаблонные эксперименты, не все несут данные.');
md.push('- Часть провайдеров требует собственных API-ключей; без ключа их возможности недоступны.');
md.push('- Реестр архитектурных решений (ADR) и каталог внешних библиотек пока не выделены (см. [[dev-system-map]]).');
md.push('- Одна панель навигации без статьи вики (`dashboard`) — см. [[docs-health]].');
md.push('');
md.push('## Диагностика');
md.push('');
md.push('- Список диагностических панелей — [[diagnostics]].');
md.push('- Здоровье документации и ссылок — [[docs-health]].');
md.push('- Факты и статусы — по [[docs-standard]]; провенанс — [[docs-inventory]].');
md.push('');

writeFileSync(
    resolve(genDir, 'wiki-capabilities.ts'),
    `// Generated by node scripts/gen-wiki-capabilities.mjs — do not hand-edit.\nexport const CAPABILITIES_MARKDOWN: string = ${JSON.stringify(md.join('\n'))};\n`,
);
console.log(
    `capabilities: ${sections.length} areas, ${sections.reduce((a, s) => a + s.items.length, 0)} panels, ${mermaidCount} mermaid -> src/generated/wiki-capabilities.ts`,
);
