// Generator: event catalog for the wiki — every bus event from the single source
// of truth (src/kernel/events/event-registry.ts), grouped by section comment.
// Run: node scripts/gen-wiki-events.mjs  (output is generated, do not hand-edit).
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'src/kernel/events/event-registry.ts');
const outFile = resolve(root, 'src/generated/wiki-event-catalog.ts');

const text = readFileSync(src, 'utf8');
const lines = text.split(/\r?\n/);

const headerRe = /^\s*\/\/\s*(?:─+|\-{2,})\s*(.+?)\s*(?:─+|\-{2,})\s*$/;
const keyRe = /^\s{4}([A-Z][A-Z0-9_]*):\s*event\(/;
const nameSameLineRe = /event\(\s*'([^']+)'/;

const sections = [];
let current = { title: '(без раздела)', items: [] };
sections.push(current);

for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const h = line.match(headerRe);
    if (h && h[1]) {
        current = { title: h[1].trim(), items: [] };
        sections.push(current);
        continue;
    }
    const k = line.match(keyRe);
    if (k) {
        let name = null;
        const same = line.match(nameSameLineRe);
        if (same) name = same[1];
        else {
            for (let j = i + 1; j < Math.min(i + 4, lines.length); j++) {
                const m = lines[j].match(/'([^']+)'/);
                if (m) {
                    name = m[1];
                    break;
                }
            }
        }
        if (name) current.items.push({ key: k[1], name });
    }
}

const filled = sections.filter((s) => s.items.length > 0);
const total = filled.reduce((n, s) => n + s.items.length, 0);
const dupNames = new Map();
for (const s of filled) for (const it of s.items) dupNames.set(it.name, (dupNames.get(it.name) || 0) + 1);
const dups = [...dupNames.entries()].filter(([, n]) => n > 1);

const L = [];
L.push('## Каталог событий шины');
L.push('');
L.push(
    `Сгенерировано автоматически (scripts/gen-wiki-events.mjs) из реестра-источника src/kernel/events/event-registry.ts: ${total} событий в ${filled.length} разделах. EVENTS, EVENT_VALIDATORS и типы выводятся из реестра — новое событие добавляй только туда, и оно появится во всех производных экспортах.`,
);
L.push('');
L.push('```mermaid');
L.push('flowchart LR');
L.push('    Svc["Сервис / менеджер"] -- "eventBus.emit(EVENTS.X)" --> Bus["EventBus"]');
L.push('    Bus --> Reg["EVENT_REGISTRY: имя + Zod-схема"]');
L.push('    Bus -- "live" --> Sub["Подписчики (панели, сервисы)"]');
L.push('    Bus -. "ошибка доставки" .-> DLQ["Dead-letter queue (ретраи)"]');
L.push('```');
L.push('');
L.push('Шина in-memory и lossy: порядок и доставка после перезагрузки не гарантированы. Менеджеры гидрируются из durable-хранилища (Dexie/KV), а событие используют как сигнал «обнови», а не как источник правды.');
L.push('');
if (dups.length) {
    L.push(`Внимание: ${dups.length} имён зарегистрированы более одного раза (алиасы/дубли):`);
    L.push('');
    for (const [name, n] of dups) L.push(`- ${name} — ${n} раза`);
    L.push('');
}
for (const s of filled) {
    L.push(`### ${s.title} (${s.items.length})`);
    L.push('');
    L.push('| Ключ EVENTS | Имя события |');
    L.push('|---|---|');
    for (const it of s.items) L.push(`| ${it.key} | ${it.name} |`);
    L.push('');
}

const md = L.join('\n');
const out = `// Generated by node scripts/gen-wiki-events.mjs — do not hand-edit.
export const EVENT_CATALOG_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
export const EVENT_CATALOG_COUNT = ${total};
export const EVENT_CATALOG_MARKDOWN: string = ${JSON.stringify(md)};
`;
writeFileSync(outFile, out, 'utf8');
console.log(`events: ${total}, sections: ${filled.length}, duplicates: ${dups.length}, markdown: ${md.length} chars`);
