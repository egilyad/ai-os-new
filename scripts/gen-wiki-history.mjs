// Stage 5 generator: the development history page — zones, audits and the
// decision/plan archive, built from docs/manifest.json (zones live as wiki
// articles) and docs/inventory.json (audits + history files). Originals are
// never rewritten: this page only indexes them and points to sources.
// Run: node scripts/gen-wiki-history.mjs
// Output: src/generated/wiki-history.ts -> DEVELOPMENT_HISTORY_MARKDOWN
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const genDir = resolve(root, 'src/generated');
mkdirSync(genDir, { recursive: true });

const REPO = 'https://github.com/egilyad/ai-os-new';
const gh = (p) => `${REPO}/blob/main/${p}`;
const tree = (p) => `${REPO}/tree/main/${p}`;

const manifest = JSON.parse(readFileSync(resolve(root, 'docs/manifest.json'), 'utf8'));
const inventory = JSON.parse(readFileSync(resolve(root, 'docs/inventory.json'), 'utf8'));
const model = JSON.parse(readFileSync(resolve(root, 'docs/entity-model.json'), 'utf8'));

const zones = manifest.articles
    .filter((a) => /^zone-\d+$/.test(a.slug))
    .sort((a, b) => Number(a.slug.slice(5)) - Number(b.slug.slice(5)));
const audits = inventory.documents.filter((d) => d.category === 'audits');
const rootAudits = audits.filter((d) => d.path.split('/').length === 3);
const grouped = {};
for (const d of audits) {
    const seg = d.path.split('/');
    const key = seg.length > 3 ? seg[2] + '/' : 'корень';
    (grouped[key] ??= []).push(d);
}
const history = inventory.documents.filter((d) => d.category === 'history');
const histDirs = [...new Set(history.map((d) => d.path.split('/')[2]).filter((s) => s && !s.endsWith('.md')))];

const md = [];
md.push('# История разработки');
md.push('');
md.push('> Автосгенерировано `scripts/gen-wiki-history.mjs` из `docs/manifest.json` и `docs/inventory.json`. Не редактировать вручную.');
md.push('');
md.push('Как развивался проект и где это зафиксировано. Правила сохранности — в [[docs-standard]].');
md.push('**Важно:** это запись о прошлой работе, а не описание текущего кода; текущее состояние —');
md.push('в каталогах (см. [[docs-index]]).');
md.push('');
md.push(`## Хроника: зоны (${zones.length})`);
md.push('');
md.push('Волны работы проекта, по одной странице на зону:');
md.push('');
md.push(zones.map((z) => `[[${z.slug}]]`).join(' · '));
md.push('');
md.push('Каждая зона — отчёт о проделанном на тот момент. Не выдаётся за текущее состояние.');
md.push('');
md.push(`## Аудиты (${audits.length})`);
md.push('');
md.push('Отчёты проверок сохраняются как есть:');
md.push('');
for (const [key, list] of Object.entries(grouped)) {
    if (key === 'корень') {
        for (const d of list) md.push(`- [${d.title || d.path}](${gh(d.path)})`);
    } else {
        md.push(`- папка [\`docs/audits/${key}\`](${tree('docs/audits/' + key)}) — ${list.length}`);
    }
}
md.push('');
md.push(`Всего отчётов: **${audits.length}** (в корне — ${rootAudits.length}).`);
md.push('');
md.push(`## Архив решений и планов (${history.length})`);
md.push('');
md.push(`Материалы прежних решений и планов: [\`docs/history/\`](${tree('docs/history')}).`);
if (histDirs.length) {
    md.push('');
    md.push('Подпапки: ' + histDirs.map((d) => `[\`${d}/\`](${tree('docs/history/' + d)})`).join(', ') + '.');
}
md.push('');
md.push('Реестр архитектурных решений (ADR) пока не выделен — это отдельный пункт плана ([[docs-index]]).');
md.push('');
md.push('## Регрессии и известные проблемы');
md.push('');
md.push('- Регрессионные тесты — в [[dev-tests-catalog]]; прогон в CI, см. [[docs-health]].');
md.push('- Отдельные известные проблемы фиксируются в отчётах (`docs/audits/`, зоны) и не переписываются задним числом.');
md.push('');
md.push('## Правила этой страницы');
md.push('');
for (const r of model.historyRules) md.push(`- ${r}`);
md.push('');

writeFileSync(
    resolve(genDir, 'wiki-history.ts'),
    `// Generated by node scripts/gen-wiki-history.mjs — do not hand-edit.\nexport const DEVELOPMENT_HISTORY_MARKDOWN: string = ${JSON.stringify(md.join('\n'))};\n`,
);
console.log(
    `dev history: ${zones.length} zones, ${audits.length} audits, ${history.length} history docs -> src/generated/wiki-history.ts`,
);
