// Generator: tooling catalog for the wiki — npm scripts and the purpose (header
// comment) of every scripts/ + cli/ + server/ file.
// Run: node scripts/gen-wiki-scripts.mjs  (output is generated, do not hand-edit).
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function purpose(text) {
    const lines = text.replace(/^#![^\n]*\n/, '').split(/\r?\n/);
    for (const l of lines) {
        const t = l.trim();
        if (!t) continue;
        if (t.startsWith('//')) return t.replace(/^\/\/\s?/, '').trim();
        if (t.startsWith('/*') || t.startsWith('*')) return t.replace(/^\/\*+\s?/, '').replace(/\*\/$/, '').trim();
        if (t.startsWith('#')) return t.replace(/^#\s?/, '').trim();
        break;
    }
    return '—';
}

function cell(s) {
    return String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
}

function listing(dirName) {
    const dir = resolve(root, dirName);
    if (!existsSync(dir)) return [];
    return readdirSync(dir)
        .filter((n) => /\.(mjs|cjs|js|ts|py)$/.test(n) && !/\.test\./.test(n))
        .sort()
        .map((n) => ({ file: `${dirName}/${n}`, purpose: purpose(readFileSync(resolve(dir, n), 'utf8')) }));
}

const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const scripts = Object.entries(pkg.scripts || {}).sort((a, b) => a[0].localeCompare(b[0]));

const L = [];
L.push('## Скрипты и CLI');
L.push('');
L.push(
    'Как запускать и чинить ОС: команды из package.json и назначение служебных файлов (по первой строке-комментарию в каждом). Полный гейт качества — см. [[dev-ci]]; генераторы вики — см. [[dev-generators]].',
);
L.push('');
L.push('### npm-скрипты');
L.push('');
L.push('| Команда | Выполняет |');
L.push('|---|---|');
for (const [name, cmd] of scripts) {
    const shown = cmd.length > 150 ? cmd.slice(0, 147) + '…' : cmd;
    L.push(`| npm run ${name} | ${cell(shown)} |`);
}
L.push('');

for (const [title, dirName, note] of [
    ['Генераторы и утилиты (scripts/)', 'scripts', 'генераторы данных вики, readme-карт, токенизация цветов, smoke, прокси, sidecar-ctl'],
    ['CLI (cli/)', 'cli', 'единая точка входа superagents'],
    ['Сервер (server/)', 'server', 'sync-server, dev-хост, адаптеры browser/computer, write-queue, ws-auth'],
]) {
    const items = listing(dirName);
    if (items.length === 0) continue;
    L.push(`### ${title}`);
    L.push('');
    L.push(note + '.');
    L.push('');
    L.push('| Файл | Назначение |');
    L.push('|---|---|');
    for (const it of items) L.push(`| ${it.file} | ${cell(it.purpose)} |`);
    L.push('');
}

const md = L.join('\n');
const out = `// Generated by node scripts/gen-wiki-scripts.mjs — do not hand-edit.
export const SCRIPTS_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
export const SCRIPTS_COUNT = ${scripts.length};
export const SCRIPTS_MARKDOWN: string = ${JSON.stringify(md)};
`;
writeFileSync(resolve(root, 'src/generated/wiki-scripts.ts'), out, 'utf8');
console.log(`npm scripts: ${scripts.length}, markdown=${md.length} chars`);
