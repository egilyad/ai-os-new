// Generator: i18n catalog for the wiki — keys per namespace (en vs ru) and the
// top-level key prefixes, so readers/nets can find where a string lives.
// Run: node scripts/gen-wiki-i18n.mjs  (output is generated, do not hand-edit).
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const enDir = resolve(root, 'src/i18n/translations/en');
const ruDir = resolve(root, 'src/i18n/translations/ru');

function namespaces(dir) {
    return readdirSync(dir)
        .filter((n) => n.endsWith('.ts') && n !== 'index.ts')
        .map((n) => n.replace(/\.ts$/, ''))
        .sort();
}

function keysOf(file) {
    const text = readFileSync(file, 'utf8');
    const keys = [];
    const re = /^\s*'([^']+)'\s*:/gm;
    let m;
    while ((m = re.exec(text)) !== null) keys.push(m[1]);
    return keys;
}

const ns = namespaces(enDir);
const rows = [];
let totalEn = 0;
let totalRu = 0;
for (const name of ns) {
    const enKeys = keysOf(resolve(enDir, `${name}.ts`));
    const ruKeys = keysOf(resolve(ruDir, `${name}.ts`));
    totalEn += enKeys.length;
    totalRu += ruKeys.length;
    const prefixes = new Map();
    for (const k of enKeys) {
        const p = k.includes('.') ? k.split('.')[0] : k;
        prefixes.set(p, (prefixes.get(p) || 0) + 1);
    }
    const top = [...prefixes.entries()].sort((a, b) => b[1] - a[1]);
    rows.push({ name, en: enKeys.length, ru: ruKeys.length, prefixes: top });
}

const parity = totalEn === totalRu ? 'совпадает' : `РАСХОЖДЕНИЕ (${totalEn} vs ${totalRu})`;

const L = [];
L.push('## Локализация (i18n)');
L.push('');
L.push(
    `Словари разбиты по неймспейсам-файлам (src/i18n/translations/{en,ru}/<namespace>.ts), каждый — плоский Record<string,string>, склеиваются через spread в index.ts. Всего ${ns.length} неймспейсов, ${totalEn} ключей (en) / ${totalRu} (ru), паритет: ${parity}. Паритет наборов ключей en↔ru проверяет тест src/i18n/i18n-keys.test.ts.`,
);
L.push('');
L.push('```mermaid');
L.push('flowchart LR');
L.push('    K["useTranslation().t(key)"] --> EN["en/<ns>.ts"]');
L.push('    K --> RU["ru/<ns>.ts"]');
L.push('    EN --> P["i18n-keys.test.ts — паритет"]');
L.push('    RU --> P');
L.push('```');
L.push('');
L.push('### Ключи по неймспейсам');
L.push('');
L.push('| Неймспейс | Ключей (en) | Ключей (ru) |');
L.push('|---|---|---|');
for (const r of rows) L.push(`| ${r.name} | ${r.en} | ${r.ru} |`);
L.push('');
L.push('### Префиксы ключей (en)');
L.push('');
L.push('Верхний уровень ключа до первой точки — сгруппирован по неймспейсу.');
L.push('');
for (const r of rows) {
    const list = r.prefixes.map(([p, c]) => `${p} (${c})`).join(', ');
    L.push(`**${r.name}** — ${list}`);
    L.push('');
}

const md = L.join('\n');
const out = `// Generated by node scripts/gen-wiki-i18n.mjs — do not hand-edit.
export const I18N_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
export const I18N_KEY_COUNT = ${totalEn};
export const I18N_MARKDOWN: string = ${JSON.stringify(md)};
`;
writeFileSync(resolve(root, 'src/generated/wiki-i18n.ts'), out, 'utf8');
console.log(`namespaces: ${ns.length}, keys en=${totalEn} ru=${totalRu}, markdown=${md.length} chars`);
