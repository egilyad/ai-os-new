function machineTranslate(text) {
    if (!text || text.trim() === '') return '';
    const words = text.split(/(?<=[a-z])(?=[A-Z])|[\s_-]+/);
    const translated = words
        .map((w) => {
            if (!w) return '';
            const lower = w.toLowerCase();
            const capital = w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();
            if (ruDict[w]) return ruDict[w];
            if (ruDict[capital]) return ruDict[capital];
            if (ruDict[lower]) return ruDict[lower];
            return w;
        })
        .filter(Boolean)
        .join(' ');
    return translated.trim();
}

// Build ru translations map
const result = new Map();
for (const [key, enValue] of enKeys) {
    const keyParts = key.split('.').pop() || key;
    const keyWords = keyParts.replace(/[_]/g, ' ');
    const translated = machineTranslate(keyWords);
    result.set(key, translated || keyParts);
}

// Write ru.ts
const lines = ['const ru = {'];
for (const [key, value] of result) {
    lines.push(`    '${key}': '${value.replace(/'/g, "\\'")}',`);
}
lines.push('};');
lines.push('');
lines.push('export { ru };');
lines.push('');

writeFileSync('src/i18n/translations/ru.ts', lines.join('\n'), 'utf-8');
