// Generator: stores catalog for the wiki — every exported hook/creator/type in
// src/stores, with the state type it is created for.
// Run: node scripts/gen-wiki-stores.mjs  (output is generated, do not hand-edit).
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'src/stores');

const files = readdirSync(dir)
    .filter((n) => n.endsWith('.ts') && !n.endsWith('.test.ts'))
    .sort();

const exportRe = /export\s+(const|function|class|interface|type|enum)\s+([A-Za-z0-9_]+)/g;
const stateRe = /create(?:Store)?\s*<\s*([A-Za-z0-9_]+)/;

const rows = [];
let hooks = 0;
for (const name of files) {
    const text = readFileSync(resolve(dir, name), 'utf8');
    const exportsList = [];
    exportRe.lastIndex = 0;
    let m;
    while ((m = exportRe.exec(text)) !== null) {
        const kind = m[1];
        const id = m[2];
        const isHook = kind === 'const' && /^use/.test(id);
        if (isHook) hooks++;
        exportsList.push({ kind: isHook ? 'hook' : kind, name: id });
    }
    const stateMatch = text.match(stateRe);
    rows.push({ file: `src/stores/${name}`, exports: exportsList, state: stateMatch ? stateMatch[1] : '—' });
}

const totalExports = rows.reduce((n, r) => n + r.exports.length, 0);

const L = [];
L.push('## Сторы (состояние UI)');
L.push('');
L.push(
    `Состояние слоя Application: ${files.length} файлов в src/stores, ${hooks} хуков-сторов (Zustand-подобных), ${totalExports} экспортов. Стор держит UI-состояние; источник правды для durable-данных — сервис/БД, а стор — кэш для рендера.`,
);
L.push('');
L.push('```mermaid');
L.push('flowchart LR');
L.push('    P["Панель"] --> St["Стор (src/stores)"]');
L.push('    St --> Sv["Kernel-сервис"]');
L.push('    Sv --> DB["Dexie / KV (источник правды)"]');
L.push('    Bus["EventBus"] -. "live-сигнал" .-> St');
L.push('```');
L.push('');
L.push('| Файл | Хук/экспорт | Тип | Тип состояния |');
L.push('|---|---|---|---|');
for (const r of rows) {
    if (r.exports.length === 0) {
        L.push(`| ${r.file} | — | — | ${r.state} |`);
        continue;
    }
    r.exports.forEach((e, i) => {
        const fileCell = i === 0 ? r.file : '';
        const stateCell = i === 0 ? r.state : '';
        L.push(`| ${fileCell} | ${e.name} | ${e.kind} | ${stateCell} |`);
    });
}

const md = L.join('\n');
const out = `// Generated by node scripts/gen-wiki-stores.mjs — do not hand-edit.
export const STORES_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
export const STORES_HOOK_COUNT = ${hooks};
export const STORES_MARKDOWN: string = ${JSON.stringify(md)};
`;
writeFileSync(resolve(root, 'src/generated/wiki-stores.ts'), out, 'utf8');
console.log(`store files: ${files.length}, hooks: ${hooks}, exports: ${totalExports}, markdown: ${md.length} chars`);
