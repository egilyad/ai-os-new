// Stage 3 generator: the documentation map — a single entry point to the whole
// documentation, built from the machine-readable index (docs/manifest.json) and
// the full inventory (docs/inventory.json).
// Run: node scripts/gen-wiki-docs-index.mjs
// Output: src/generated/wiki-docs-index.ts -> DOCS_INDEX_MARKDOWN
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const genDir = resolve(root, 'src/generated');
mkdirSync(genDir, { recursive: true });

const REPO = 'https://github.com/egilyad/ai-os-new';
const gh = (p) => `${REPO}/blob/main/${p}`;

const manifest = JSON.parse(readFileSync(resolve(root, 'docs/manifest.json'), 'utf8'));
const inventory = JSON.parse(readFileSync(resolve(root, 'docs/inventory.json'), 'utf8'));
const byCat = (c) => inventory.documents.filter((d) => d.category === c);
const bySection = (id) => manifest.articles.filter((a) => a.section === id);

const md = [];
md.push('# Карта документации');
md.push('');
md.push('> Автосгенерировано `scripts/gen-wiki-docs-index.mjs` из `docs/manifest.json` и `docs/inventory.json`.');
md.push('> Не редактировать вручную.');
md.push('');
md.push('Единый вход во всю документацию проекта: что где искать и откуда берутся данные.');
md.push('Правила и статусы — в [[docs-standard]]; состояние — в [[docs-health]]; состав — в [[docs-inventory]].');
md.push('');
md.push('## Быстрый вход');
md.push('');
md.push(`- [README (RU)](${gh('README.md')}) · [README (EN)](${gh('README_EN.md')}) — обзор и вики-карта`);
md.push('- Панель **Wiki** в приложении и сайт `/wiki/` — тот же корпус статей');
md.push(`- [\`docs/manifest.json\`](${gh('docs/manifest.json')}) — машиночитаемый индекс сущностей (статьи, панели)`,);
md.push(`- [\`docs/entity-model.json\`](${gh('docs/entity-model.json')}) — стандарт документации`);
md.push(`- [\`docs/inventory.json\`](${gh('docs/inventory.json')}) — инвентарь всех \`docs/**\` (${inventory.totals.documents} документов)`);
md.push('');
md.push('## Вики по разделам');
md.push('');
for (const s of manifest.sections) {
    const arts = bySection(s.id);
    md.push(`**${s.title}** — ${arts.length}: ${arts.map((a) => `[[${a.slug}]]`).join(' · ')}`);
    md.push('');
}
md.push(`Всего статей вики: **${manifest.articles.length}** в ${manifest.sections.length} разделах.`);
md.push('');
md.push('## Документация верхнего уровня');
md.push('');
md.push('Крупные документы в корне `docs/`:');
md.push('');
for (const d of byCat('top')) md.push(`- [${d.title || d.path}](${gh(d.path)})`);
md.push('');
md.push('## Справочники и планы');
md.push('');
md.push('**Нормативные справочники:**');
for (const d of byCat('reference')) md.push(`- [${d.title || d.path}](${gh(d.path)})`);
md.push('');
md.push('**Планы и направления** (не текущее состояние):');
for (const d of byCat('roadmap')) md.push(`- [${d.title || d.path}](${gh(d.path)})`);
md.push('');
md.push('## Архив: история и аудиты');
md.push('');
md.push('Исторические материалы сохраняются без смысловой переписи (см. [[docs-standard]]).');
md.push('');
md.push(`- аудиты: **${byCat('audits').length}** — [\`docs/audits/\`](${REPO}/tree/main/docs/audits)`);
md.push(`- история/зоны: **${byCat('history').length}** — [\`docs/history/\`](${REPO}/tree/main/docs/history)`);
md.push(`- заменённое: **${byCat('superseded').length}** — [\`docs/superseded/\`](${REPO}/tree/main/docs/superseded)`);
md.push(`- текущее рабочее: **${byCat('active').length}** — [\`docs/active/\`](${REPO}/tree/main/docs/active)`);
md.push('');
md.push('Полный список каждого документа — в `docs/inventory.json` и в [[docs-inventory]].');
md.push('');
md.push('## Проверки');
md.push('');
md.push('- `npm run docs:health` — ссылки, источники, панели, манифест, схема; статья [[docs-health]].');
md.push('- `npm run gen:wiki-docs-index` — эта карта; список всех генераторов — [[dev-generators]].');

writeFileSync(
    resolve(genDir, 'wiki-docs-index.ts'),
    `// Generated by node scripts/gen-wiki-docs-index.mjs — do not hand-edit.\nexport const DOCS_INDEX_MARKDOWN: string = ${JSON.stringify(md.join('\n'))};\n`,
);
console.log(
    `docs index: ${manifest.articles.length} articles in ${manifest.sections.length} sections, ` +
        `${inventory.totals.documents} documents -> src/generated/wiki-docs-index.ts`,
);
